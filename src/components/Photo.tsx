import React from 'react';
import manifest from '../content/image-manifest.json';

export type PhotoName = keyof typeof manifest;

interface PhotoProps {
  name: PhotoName;
  alt: string;
  /** the `sizes` attribute: how wide the photo is shown, e.g. "(max-width: 768px) 90vw, 30vw" */
  sizes: string;
  className?: string;
  /** CSS object-position for the crop */
  position?: string;
  /** above-the-fold photo: load immediately with high priority */
  priority?: boolean;
  /** pick the largest file regardless of `sizes` (lightbox) */
  largest?: boolean;
}

export const photoSrc = (name: PhotoName, width?: number) => {
  const { widths } = manifest[name];
  const w = width ?? widths[widths.length - 1];
  return `/images/${name}-${w}.webp`;
};

/** Responsive WebP photo generated by scripts/optimize-images.mjs */
const Photo: React.FC<PhotoProps> = ({ name, alt, sizes, className, position, priority, largest }) => {
  const { widths, ratio } = manifest[name];
  const maxW = widths[widths.length - 1];
  return (
    <img
      className={className}
      src={photoSrc(name, largest ? maxW : widths[Math.min(1, widths.length - 1)])}
      srcSet={largest ? undefined : widths.map((w) => `${photoSrc(name, w)} ${w}w`).join(', ')}
      sizes={largest ? undefined : sizes}
      width={maxW}
      height={Math.round(maxW / ratio)}
      alt={alt}
      loading={priority ? 'eager' : 'lazy'}
      decoding={priority ? 'sync' : 'async'}
      {...(priority ? { fetchpriority: 'high' } : {})}
      style={position ? { objectPosition: position } : undefined}
      draggable={false}
    />
  );
};

export default Photo;
